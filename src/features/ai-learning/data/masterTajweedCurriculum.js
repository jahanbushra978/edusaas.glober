/**
 * Helper to fetch a lesson by ID across all levels and units
 */
export function getLessonById(lessonId) {
  if (!lessonId) return null;
  for (const unit of MASTER_TAJWEED_UNITS) {
    const found = unit.lessons.find((l) => l.id === lessonId);
    if (found) {
      return { ...found, unit };
    }
  }
  return null;
}

/**
 * Returns total count of lessons and units
 */
export function getCurriculumStats() {
  let totalLessons = 0;
  for (const unit of MASTER_TAJWEED_UNITS) {
    totalLessons += unit.lessons.length;
  }
  return {
    totalLevels: TAJWEED_LEVELS.length,
    totalUnits: MASTER_TAJWEED_UNITS.length,
    totalLessons,
  };
}

