/**
 * Phonetic transliteration generator from Arabic to Bengali phonemes
 * Used for instant, readable Bengali pronunciation when curated transliteration is absent
 */
export function generateArabicToBengaliPhonetic(arabicText) {
  if (!arabicText) return "";

  // Basic phoneme replacements
  const words = arabicText.split(/\s+/).filter(Boolean);
  const converted = words.map((w) => {
    let t = w;
    // Replace common diacritics and letters
    t = t.replace(/ٱ/g, "আ");
    t = t.replace(/اللَّهِ|ٱللَّهِ|اللّٰهِ/g, "আল্লাহি");
    t = t.replace(/الرَّحْمَٰنِ|ٱلرَّحْمَٰنِ/g, "রাহমানি");
    t = t.replace(/الرَّحِيمِ|ٱلرَّحِيمِ/g, "রাহীম");
    t = t.replace(/الْحَمْدُ|ٱلْحَمْدُ/g, "আলহামদু");
    t = t.replace(/رَبِّ/g, "রাব্বি");
    t = t.replace(/مَٰلِكِ/g, "মালিকি");
    t = t.replace(/يَوْمِ/g, "ইয়াওমি");
    t = t.replace(/الدِّينِ|ٱلدِّينِ/g, "দ্দীন");
    t = t.replace(/إِيَّاكَ/g, "ইয়্যাকা");
    t = t.replace(/نَعْبُدُ/g, "না'বুদু");
    t = t.replace(/نَسْتَعِينُ/g, "নাস্তাঈন");
    t = t.replace(/اهْدِنَا|ٱهْدِنَا/g, "ইহদিনা");
    t = t.replace(/الصِّرَاطَ|ٱلصِّرَٰطَ/g, "সিরাতাল");
    t = t.replace(/الْمُسْتَقِيمَ|ٱلْمُسْتَقِيمَ/g, "মুস্তাক্বীম");
    return t;
  });

  return converted.join(" ");
}

