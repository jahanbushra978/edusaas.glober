// Manzil Division (৭টি মনজিল)
export function getManzilForSurah(surahId) {
  const s = Number(surahId) || 1;
  if (s <= 4) return 1;
  if (s <= 9) return 2;
  if (s <= 16) return 3;
  if (s <= 25) return 4;
  if (s <= 36) return 5;
  if (s <= 49) return 6;
  return 7;
}

// Convert English digits to Bengali digits
export const toBnNum = (num) => {
  if (num === null || num === undefined) return "০";
  const enToBn = { "0":"০", "1":"১", "2":"২", "3":"৩", "4":"৪", "5":"৫", "6":"৬", "7":"৭", "8":"৮", "9":"৯" };
  return String(num).replace(/\d/g, (d) => enToBn[d] || d);
};

// Convert English digits to Arabic/Urdu digits
export const toArNum = (num) => {
  if (num === null || num === undefined) return "٠";
  const enToAr = { "0":"٠", "1":"١", "2":"٢", "3":"٣", "4":"٤", "5":"٥", "6":"٦", "7":"٧", "8":"٨", "9":"٩" };
  return String(num).replace(/\d/g, (d) => enToAr[d] || d);
};

/**
 * Canonical Quranic Arabic Phonetic & Orthographic Normalizer
 * Bridges the gap between Uthmani script (رسم عثماني) and Imla'i modern Arabic (رسم إملائي).
 * Normalizes dagger alifs (\u0670), wasla (\u0671), hamzated alifs, alif maqsurah, and diacritics.
 */
export function normalizeQuranWord(str) {
  if (!str) return "";
  let s = String(str)
    .replace(/\u0671/g, "ا") // wasla -> alif
    .replace(/[\u0622\u0623\u0625\u0672\u0673\u0675]/g, "ا") // hamzated alif -> alif
    .replace(/ءا/g, "ا") // hamza + alif -> alif
    .replace(/\u0649\u0670/g, "ي") // alif maksura + dagger alif -> ya
    .replace(/\u0670/g, "ا") // dagger alif -> alif
    .replace(/[\u064B-\u065F\u06D6-\u06ED\u0610-\u061A]/g, "") // strip all diacritics & waqf glyphs
    .replace(/[\u0649]/g, "ي") // alif maqsurah -> ya
    .replace(/\u0629/g, "ه") // ta marbuta -> ha
    .replace(/[ءؤئ]/g, "") // remove standalone/carrier hamza
    .replace(/[\s\-_ـ\.\,\:\;]+/g, "")
    .trim();

  // Canonical Uthmani ligature exceptions
  s = s.replace(/اولا+ك/g, "اولك"); // 'أولئك'
  s = s.replace(/هـ?ذا+/g, "هذا");
  s = s.replace(/هـ?ذه+/g, "هذه");
  s = s.replace(/هـ?ؤلا+ء/g, "هولاء");
  s = s.replace(/لـ?كن/g, "لكن");
  s = s.replace(/يـ?ايها/g, "ياايها");
  s = s.replace(/يا+يها/g, "ياايها");
  s = s.replace(/يا+بتي/g, "ياابتي");
  s = s.replace(/يا+ابتي/g, "ياابتي");
  s = s.replace(/يا+قوم/g, "ياقوم");
  s = s.replace(/يا+بني/g, "يابني");
  s = s.replace(/يا+ويلتي/g, "ياويلتي");
  s = s.replace(/يا+حسرتي/g, "ياحسرتي");
  return s;
}

/**
 * 1. Page Header Metadata Builder
 * - Right: Surah Name, Surah Number, Para Number, Para Page Number
 * - Left: Para Name (Arabic), Manzil Number
 * - Center: Global Hafizi Page Number
 */
export function getHafiziHeaderMetadata(pageNum, paraInfo, currentSurah) {
  const p = paraInfo || HAFIZI_PARAS[0];
  const s = currentSurah || ALL_SURAHS[0];
  const manzil = getManzilForSurah(s.id);
  const paraPage = Math.max(1, (pageNum - p.startPage) + 1);

  return {
    // Right Header (Arabic & Bengali layout)
    headerRightAr: `سُوْرَةُ ${s.nameAr} ${toArNum(s.id)} - پاره ${toArNum(p.juz)} - صفحه ${toArNum(paraPage)}`,
    headerRightBn: `সূরা ${s.nameBn} (${toBnNum(s.id)}) • পারা ${toBnNum(p.juz)} • পৃষ্ঠা ${toBnNum(paraPage)}`,
    
    // Left Header
    headerLeftAr: `${p.nameAr} - مَنْزِل ${toArNum(manzil)}`,
    headerLeftBn: `${p.nameBn} • মনজিল ${toBnNum(manzil)}`,

    // Center Global Page
    centerPageBn: toBnNum(pageNum),
    centerPageAr: toArNum(pageNum),
    globalPage: pageNum,
    para: p.juz,
    paraPage,
    manzil,
  };
}

