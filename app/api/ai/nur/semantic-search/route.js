// Module-level in-memory cache for Ayah Uthmani text & Bengali translation
const AYAH_EDITIONS_CACHE = new Map();

async function getHydratedAyah(surahNum, ayahNum) {
  const key = `${surahNum}:${ayahNum}`;
  if (AYAH_EDITIONS_CACHE.has(key)) {
    return AYAH_EDITIONS_CACHE.get(key);
  }
  try {
    const res = await fetch(`https://api.alquran.cloud/v1/ayah/${key}/editions/quran-uthmani,bn.bengali`, {
      next: { revalidate: 86400 }
    });
    if (res.ok) {
      const data = await res.json();
      const val = {
        arabic: data?.data?.[0]?.text || "",
        bangla: data?.data?.[1]?.text || ""
      };
      if (val.arabic) {
        AYAH_EDITIONS_CACHE.set(key, val);
      }
      return val;
    }
  } catch (e) {
    console.warn(`Failed hydrating ayah ${key}:`, e);
  }
  return { arabic: "", bangla: "" };
}

export async function POST(request) {
  try {
    const isCsrfSafe = await verifyCsrfOrigin(request);
    if (!isCsrfSafe) {
      return NextResponse.json({ ok: false, message: "CSRF verification failed" }, { status: 403 });
    }

    const body = await request.json().catch(() => ({}));
    const { query = "" } = body;

    const rawQuery = (query || "").trim();
    if (!rawQuery) {
      return NextResponse.json({ ok: true, matchesCount: 0, results: [] });
    }

    const isArabic = /[\u0600-\u06FF]/.test(rawQuery);
    const isBengali = /[\u0980-\u09FF]/.test(rawQuery);
    const isEnglish = /^[a-zA-Z0-9\s\-_.,'"?!]+$/.test(rawQuery);

    // 1. If not Arabic, check canonical thematic categories first (e.g. সালাত, সবর, ইত্যাদি)
    if (!isArabic) {
      const lowerQuery = rawQuery.toLowerCase();
      for (const item of CANONICAL_THEMATIC_INDEX) {
        const matchesCategory = item.keywords.some((kw) => {
          const lkw = kw.toLowerCase();
          return lowerQuery === lkw || (lowerQuery.length >= 3 && lkw.includes(lowerQuery));
        });
        if (matchesCategory) {
          return NextResponse.json({
            ok: true,
            theme: item.theme,
            titleBn: item.titleBn,
            totalMatches: item.verses.length,
            matchesCount: item.verses.length,
            results: item.verses
          });
        }
      }
    }

    // 2. Full Quran Multi-Lingual Search (Arabic, Bengali, English)
    let searchEdition = "bn.bengali";
    let searchTerm = rawQuery;

    if (isArabic) {
      searchEdition = "quran-simple";
      // Remove Arabic diacritics / tashkeel (fatha, damma, kasra, sukun, shaddah, etc.)
      const noHarakat = rawQuery.replace(/[\u064B-\u065F\u0670\u06D6-\u06ED]/g, "").trim();
      searchTerm = noHarakat || rawQuery;
    } else if (isEnglish) {
      searchEdition = "en.sahih";
    } else if (isBengali) {
      searchEdition = "bn.bengali";
    }

    try {
      let searchUrl = `https://api.alquran.cloud/v1/search/${encodeURIComponent(searchTerm)}/all/${searchEdition}`;
      let res = await fetch(searchUrl, { next: { revalidate: 3600 } });
      let searchData = res.ok ? await res.json() : null;

      // In Arabic, if no results with stripped harakat, try normalized Alef
      if (isArabic && (!searchData?.data?.matches || searchData.data.matches.length === 0)) {
        const normAlef = searchTerm.replace(/[إأآٱ]/g, "ا");
        if (normAlef !== searchTerm) {
          const fallbackUrl = `https://api.alquran.cloud/v1/search/${encodeURIComponent(normAlef)}/all/${searchEdition}`;
          const fbRes = await fetch(fallbackUrl, { next: { revalidate: 3600 } });
          if (fbRes.ok) {
            searchData = await fbRes.json();
          }
        }
      }

      if (searchData?.data?.matches && searchData.data.matches.length > 0) {
        const rawMatches = searchData.data.matches;
        const totalCount = searchData.data.count || rawMatches.length;

        // Take top 40 matches
        const topMatches = rawMatches.slice(0, 40);

        // Hydrate all matches with authentic Uthmani script and verified Bengali translation in parallel
        const hydratedResults = await Promise.all(
          topMatches.map(async (m) => {
            const surahNum = m.surah?.number || 1;
            const ayahNum = m.numberInSurah || 1;
            const hydrated = await getHydratedAyah(surahNum, ayahNum);

            return {
              surah: surahNum,
              ayah: ayahNum,
              surahNameBn: getSurahNameBn(surahNum),
              arabic: hydrated.arabic || m.text || "",
              bangla: hydrated.bangla || (isBengali ? m.text : ""),
              matchedWord: rawQuery
            };
          })
        );

        return NextResponse.json({
          ok: true,
          theme: "universal_search",
          query: rawQuery,
          searchLang: isArabic ? "ar" : isEnglish ? "en" : "bn",
          totalMatches: totalCount,
          matchesCount: hydratedResults.length,
          results: hydratedResults
        });
      }
    } catch (searchErr) {
      console.warn("Live Quran search API error:", searchErr);
    }

    // 3. If nothing matched
    return NextResponse.json({
      ok: true,
      theme: "not_found",
      query: rawQuery,
      totalMatches: 0,
      matchesCount: 0,
      results: [],
      message: `"${rawQuery}" দিয়ে কুরআনে কোনো সরাসরি আয়াত পাওয়া যায়নি। বানান সঠিক কিনা বা অন্য ভাষায় লিখে আবার চেষ্টা করুন।`
    });
  } catch (err) {
    console.error("semantic-search API error:", err);
    return NextResponse.json({ ok: false, message: err.message || "Internal server error" }, { status: 500 });
  }
}
